/*
 * Renders the Reqr "Interview Results" branded assessment as a scrollable web
 * document that also prints 1:1 to US Letter (see report.css). Pure server
 * component — the only client code is the PrintButton in the toolbar.
 *
 * Pagination: each <section class="report-page"> is one printed page
 * (break-after: page). Section count is fixed per report: cover, scorecard,
 * one deep-dive page per group of 3 competencies (role fit + risk calibration
 * ride on the last one), and the final recommendation — so footers carry
 * static "Page N of M" numbers.
 */

const score10 = (n: number) => `${n.toFixed(1)}/10`;
const pct = (n: number) => `${Math.round(n)}%`;
const isWarnTier = (tier: CompetencyResult["tier"]) =>
  tier === "Developing" || tier === "Weak";

function chunk<T>(items: T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

