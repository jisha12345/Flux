// ── Document ────────────────────────────────────────────────────────────────

export default function ReportView({
  row,
  report,
  recordingUrl,
}: {
  row: AiInterviewRow;
  report: InterviewReport;
  recordingUrl: string | null;
}) {
  const compPages = chunk(report.competencies, 3);
  const totalPages = 3 + compPages.length + (report.integrity ? 1 : 0);
  const positive =
    report.verdict === "STRONG HIRE" || report.verdict === "RECOMMENDED TO PROGRESS";

  return (
    <>
      {/* Screen-only toolbar — hidden entirely when printing */}
      <header className="screen-only sticky top-0 z-20 border-b border-zinc-200 bg-white/95 backdrop-blur">
        <div className="mx-auto flex max-w-[850px] items-center justify-between gap-3 px-4 py-3 font-sans">
          <Link
            href="/employer/dashboard?tab=ai"
            className="shrink-0 text-sm font-medium text-zinc-600 transition-colors hover:text-zinc-900"
          >
            &larr; Back to dashboard
          </Link>
          <div className="flex min-w-0 items-center gap-2">
            <span className="truncate text-sm font-semibold text-zinc-900">
              {row.candidate_name}
            </span>
            <span
              className="shrink-0 rounded-sm px-2 py-0.5 text-[11px] font-bold tracking-wide"
              style={
                positive
                  ? { background: HYR.mint, color: HYR.primaryDark }
                  : { background: HYR.cream, color: HYR.amber }
              }
            >
              {report.verdict}
            </span>
          </div>
          <div className="flex shrink-0 items-center gap-2">
            {recordingUrl ? (
              <a
                href={recordingUrl}
                target="_blank"
                rel="noreferrer"
                className="rounded border border-zinc-300 px-3 py-1.5 text-xs font-semibold text-zinc-700 transition-colors hover:bg-zinc-50"
              >
                Watch recording
              </a>
            ) : null}
            <PrintButton />
          </div>
        </div>
      </header>

      <main className="hyr-doc mx-auto max-w-[850px] px-4 py-8">
        <CoverPage row={row} report={report} page={1} total={totalPages} />
        <ScorecardPage report={report} page={2} total={totalPages} />
        {compPages.map((comps, i) => {
          const last = i === compPages.length - 1;
          return (
            <DeepDivePage
              key={comps[0]?.name ?? i}
              comps={comps}
              startNumber={i * 3 + 1}
              roleTitle={row.role_title}
              roleFit={last ? report.role_fit : null}
              riskCalibration={last ? report.risk_calibration : null}
              page={3 + i}
              total={totalPages}
            />
          );
        })}
        {report.integrity ? (
          <IntegrityPage
            integrity={report.integrity}
            contentPercent={report.content_percent ?? report.overall_percent}
            adjustment={report.integrity_adjustment ?? 0}
            overallPercent={report.overall_percent}
            page={3 + compPages.length}
            total={totalPages}
          />
        ) : null}
        <FinalPage report={report} page={totalPages} total={totalPages} />
      </main>
    </>
  );
}
